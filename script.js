document.addEventListener('DOMContentLoaded', () => {

    // --- MULTI-LANGUAGE (i18n) ---
    const langBtn = document.getElementById('lang-switch');
    let currentLang = localStorage.getItem('lang') || 'tr';

    const setLanguage = (lang) => {
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[lang][key]) {
                el.innerHTML = translations[lang][key];
            }
        });
        langBtn.innerText = lang === 'tr' ? 'EN' : 'TR';
        localStorage.setItem('lang', lang);
        currentLang = lang;
        document.documentElement.lang = lang;
    };

    langBtn.addEventListener('click', () => {
        const nextLang = currentLang === 'tr' ? 'en' : 'tr';
        setLanguage(nextLang);
    });

    // Initialize Language
    setLanguage(currentLang);


    // --- MOBILE MENU TOGGLE ---
    const mobileMenu = document.getElementById('mobile-menu');
    const navLinks = document.querySelector('.nav-links');
    const navItems = document.querySelectorAll('.nav-links a');

    if (mobileMenu) {
        mobileMenu.addEventListener('click', () => {
            mobileMenu.classList.toggle('is-active');
            navLinks.classList.toggle('nav-active');
        });
    }

    // Close menu when clicking a link
    navItems.forEach(item => {
        item.addEventListener('click', () => {
            mobileMenu.classList.remove('is-active');
            navLinks.classList.remove('nav-active');
        });
    });

    // --- HEADER SCROLL ---
    const header = document.getElementById('main-header');
    window.addEventListener('scroll', () => {
        if (window.scrollY > 100) {
            header.classList.add('scrolled');
        } else {
            header.classList.remove('scrolled');
        }
    });


    // --- STATS COUNTER ---
    const stats = document.querySelectorAll('.counter');
    const animateStats = (el) => {
        const target = +el.getAttribute('data-target');
        let current = 0;
        const speed = 800; /* Faster animation */
        const increment = target / (speed / 16);

        const updateCount = () => {
            if (current < target) {
                current += increment;
                if (target >= 1000000 && current >= 1000000) {
                    el.innerText = '1M+';
                } else {
                    el.innerText = Math.ceil(current) + (target === 1000 || target === 850 ? '+' : '');
                }
                requestAnimationFrame(updateCount);
            } else {
                el.innerText = target >= 1000000 ? '1M+' : target + (target === 1000 || target === 850 ? '+' : '');
            }
        };
        updateCount();
    };


    // --- INTERSECTION OBSERVER (REVEALS) ---
    const revealElements = document.querySelectorAll('section, .service-advanced-card, .pricing-card, .stat-item, .video-card');

    const observerOptions = {
        threshold: 0.1,
        rootMargin: '0px 0px -50px 0px'
    };

    const revealObserver = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('visible');

                if (entry.target.classList.contains('stats-section')) {
                    stats.forEach(s => animateStats(s));
                }

                if (entry.target.classList.contains('stat-item')) {
                    const counter = entry.target.querySelector('.counter');
                    if (counter && !counter.classList.contains('animated')) {
                        animateStats(counter);
                        counter.classList.add('animated');
                    }
                }
            }
        });
    }, observerOptions);

    revealElements.forEach(el => {
        el.classList.add('reveal');
        revealObserver.observe(el);
    });


    // --- VIDEO HOVER (DESKTOP) & AUTO-PLAY (MOBILE) ---
    const videoCards = document.querySelectorAll('.video-card');
    const lightbox = document.getElementById('videoLightbox');
    const lightboxVideo = document.getElementById('lightboxVideo');
    const closeLightbox = document.querySelector('.close-lightbox');
    
    // Intersection Observer for mobile auto-play
    const videoObserver = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            const video = entry.target.querySelector('video');
            if (window.innerWidth <= 1024) {
                if (entry.isIntersecting) {
                    video.play();
                } else {
                    video.pause();
                }
            }
        });
    }, { threshold: 0.5 });

    videoCards.forEach(card => {
        videoObserver.observe(card);
        const video = card.querySelector('video');

        card.addEventListener('mouseenter', () => {
            if (window.innerWidth > 1024) video.play();
        });
        card.addEventListener('mouseleave', () => {
            if (window.innerWidth > 1024) {
                video.pause();
                video.currentTime = 0;
            }
        });

        card.addEventListener('click', () => {
            const videoSrc = card.getAttribute('data-video');
            lightboxVideo.src = videoSrc;
            lightbox.style.display = 'flex';
            lightboxVideo.play();
        });
    });

    closeLightbox.addEventListener('click', () => {
        lightbox.style.display = 'none';
        lightboxVideo.pause();
        lightboxVideo.src = "";
    });

    lightbox.addEventListener('click', (e) => {
        if (e.target === lightbox) {
            closeLightbox.click();
        }
    });


    // --- BACK TO TOP ---
    const backToTop = document.getElementById('backToTop');
    if (backToTop) {
        backToTop.addEventListener('click', () => {
            window.scrollTo({
                top: 0,
                behavior: 'smooth'
            });
        });
    }

    // --- PARALLAX HERO FX ---
    window.addEventListener('scroll', () => {
        const bg = document.querySelector('.hero-bg');
        const orbs = document.querySelectorAll('.orb');
        if (bg) {
            let val = window.scrollY;
            bg.style.transform = `translate3d(0, ${val * 0.35}px, 0)`;
            orbs.forEach((orb, i) => {
                orb.style.transform = `translate3d(0, ${val * (0.1 + (i * 0.05))}px, 0)`;
            });
        }
    });

    // --- STAGGERED DELAYS ---
    const gridItems = document.querySelectorAll('.services-advanced-grid > div, .pricing-grid > div, .video-grid > div');
    gridItems.forEach((item, index) => {
        item.style.animationDelay = `${(index % 5) * 0.15}s`;
    });
});
